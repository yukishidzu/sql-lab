const schemaSql = `
CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  email text NOT NULL UNIQUE,
  invited_by integer REFERENCES users(id) ON DELETE SET NULL CHECK (invited_by <> id),
  registered_at date NOT NULL
);
CREATE TABLE subscriptions (
  user_id integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  plan text NOT NULL CHECK (plan IN ('basic', 'standard', 'premium')),
  monthly_price numeric(10, 2) NOT NULL CHECK (monthly_price >= 0),
  status text NOT NULL CHECK (status IN ('active', 'expired', 'cancelled')),
  expires_at date NOT NULL
);
CREATE TABLE genres (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
CREATE TABLE movies (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  release_year integer NOT NULL CHECK (release_year BETWEEN 1900 AND 2030),
  duration_min integer NOT NULL CHECK (duration_min > 0),
  age_rating integer NOT NULL CHECK (age_rating IN (0, 6, 12, 16, 18))
);
CREATE TABLE movie_genres (
  movie_id integer NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
  genre_id integer NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
  PRIMARY KEY (movie_id, genre_id)
);
CREATE TABLE watch_history (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  movie_id integer NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
  watched_at timestamp NOT NULL,
  watched_min integer NOT NULL CHECK (watched_min >= 0),
  user_rating integer CHECK (user_rating BETWEEN 1 AND 10)
);
`

