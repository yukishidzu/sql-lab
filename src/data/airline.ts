const schemaSql = `
CREATE TABLE airports (
  code text PRIMARY KEY,
  name text NOT NULL,
  city text NOT NULL,
  country text NOT NULL
);
CREATE TABLE aircrafts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model text NOT NULL UNIQUE,
  capacity integer NOT NULL CHECK (capacity > 0),
  range_km integer NOT NULL CHECK (range_km > 0)
);
CREATE TABLE flights (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_no text NOT NULL,
  departure_airport text NOT NULL REFERENCES airports(code),
  arrival_airport text NOT NULL REFERENCES airports(code),
  aircraft_id integer NOT NULL REFERENCES aircrafts(id),
  scheduled_departure timestamp NOT NULL,
  scheduled_arrival timestamp NOT NULL CHECK (scheduled_arrival > scheduled_departure),
  actual_departure timestamp,
  actual_arrival timestamp,
  status text NOT NULL CHECK (status IN ('scheduled', 'departed', 'arrived', 'cancelled')),
  CHECK (departure_airport <> arrival_airport),
  CHECK (actual_arrival IS NULL OR (actual_departure IS NOT NULL AND actual_arrival > actual_departure))
);
CREATE TABLE bookings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_ref text NOT NULL UNIQUE,
  booked_at timestamp NOT NULL,
  total_amount numeric(10, 2) NOT NULL CHECK (total_amount >= 0)
);
CREATE TABLE tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  passenger_name text NOT NULL,
  passenger_doc text NOT NULL
);
CREATE TABLE ticket_flights (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id integer NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  flight_id integer NOT NULL REFERENCES flights(id),
  fare_class text NOT NULL CHECK (fare_class IN ('Economy', 'Comfort', 'Business')),
  price numeric(10, 2) NOT NULL CHECK (price >= 0),
  UNIQUE (ticket_id, flight_id)
);
CREATE TABLE boarding_passes (
  ticket_flight_id integer PRIMARY KEY REFERENCES ticket_flights(id) ON DELETE CASCADE,
  seat_no text NOT NULL,
  boarding_no integer NOT NULL,
  issued_at timestamp NOT NULL
);
`

