const tickets = ticketRoutes.flatMap((routes, bookingIndex) => routes.map((_, ticketIndex) => {
  const previousTickets = ticketRoutes.slice(0, bookingIndex).reduce((sum, items) => sum + items.length, 0)
  const id = previousTickets + ticketIndex + 1
  return {
    id,
    booking_id: bookingIndex + 1,
    passenger_name: passengerNames[id - 1],
    passenger_doc: `40 26 ${String(100000 + id)}`,
  }
}))

const fareClasses = ['Economy', 'Comfort', 'Business']
let nextTicketFlightId = 1
const ticketFlights = tickets.flatMap((ticket, ticketIndex) => {
  const bookingIndex = ticket.booking_id - 1
  const indexWithinBooking = ticketIndex - ticketRoutes.slice(0, bookingIndex).reduce((sum, items) => sum + items.length, 0)
  const fareClass = fareClasses[(ticket.id - 1) % fareClasses.length]
  return ticketRoutes[bookingIndex][indexWithinBooking].map((flightId) => ({
    id: nextTicketFlightId++,
    ticket_id: ticket.id,
    flight_id: flightId,
    fare_class: fareClass,
    price: (fareClass === 'Economy' ? 10000 : fareClass === 'Comfort' ? 16000 : 24000) + flightId * 500,
  }))
})

const ticketBooking = new Map(tickets.map((ticket) => [ticket.id, ticket.booking_id]))
const bookings = Array.from({ length: 14 }, (_, index) => {
  const id = index + 1
  return {
    id,
    book_ref: `BK${String(id).padStart(4, '0')}`,
    booked_at: `2026-07-${String(Math.min(index + 1, 9)).padStart(2, '0')} 09:00:00`,
    total_amount: ticketFlights.filter((segment) => ticketBooking.get(segment.ticket_id) === id).reduce((sum, segment) => sum + segment.price, 0),
  }
})

const flightById = new Map(flights.map((flight) => [flight.id, flight]))
const boardingCounters = new Map<number, number>()
const boardingPasses = ticketFlights.filter((segment) => flightById.get(segment.flight_id)?.status === 'arrived').slice(0, 35).map((segment) => {
  const flight = flightById.get(segment.flight_id)!
  const counter = (boardingCounters.get(flight.id) ?? 0) + 1
  boardingCounters.set(flight.id, counter)
  const issuedAt = new Date(`${flight.scheduled_departure.replace(' ', 'T')}Z`)
  issuedAt.setUTCMinutes(issuedAt.getUTCMinutes() - 120 + counter)
  return {
    ticket_flight_id: segment.id,
    seat_no: `${counter}A`,
    boarding_no: counter,
    issued_at: issuedAt.toISOString().replace('T', ' ').replace('.000Z', ''),
  }
})

