import { describe, expect, it } from 'vitest'
import { presets } from '../src/data/presets'

const byId = Object.fromEntries(presets.map((preset) => [preset.id, preset]))
const timestamp = (value: unknown) => new Date(`${String(value).replace(' ', 'T')}Z`).getTime()

describe('учебные пресеты', () => {
  it('содержат уровни, десять заданий и два стартовых запроса', () => {
    expect(presets.map((preset) => preset.id)).toEqual(['shop', 'cinema', 'airline'])
    expect(presets.map((preset) => preset.difficulty)).toEqual(['Базовый', 'Средний', 'Продвинутый'])
    expect(presets.map((preset) => Object.keys(preset.scenario.data).length)).toEqual([5, 6, 7])
    for (const preset of presets) {
      expect(preset.scenario.notes).toContain('## Материалы:')
      expect(preset.scenario.notes).not.toMatch(/^###\s+\d+\./gm)
      expect(preset.scenario.tasks).toHaveLength(10)
      expect(preset.scenario.tasks?.every((task) => task.referenceQuery.trim().length > 0)).toBe(true)
      expect(preset.scenario.starterQueries).toHaveLength(2)
      expect(preset.scenario).not.toHaveProperty('expectedQuery')
      expect(preset.scenario.schemaSql).not.toMatch(/\b(NOW|VARCHAR|SERIAL|BIGINT|REAL|DOUBLE PRECISION)\b/i)
    }
  })

  it('требует сортировку только там, где она входит в условие', () => {
    expect(byId.shop.scenario.tasks?.filter((task) => task.rules.compareOrder)).toHaveLength(10)
    expect(byId.cinema.scenario.tasks?.filter((task) => task.rules.compareOrder)).toHaveLength(8)
    expect(byId.airline.scenario.tasks?.filter((task) => task.rules.compareOrder)).toHaveLength(8)
  })

  it('использует оконные функции только в последней паре авиаперелётов', () => {
    const windowPattern = /\b(OVER|ROW_NUMBER|RANK|DENSE_RANK|LAG|LEAD)\s*(?:\(|$)/i
    for (const preset of [byId.shop, byId.cinema]) expect(preset.scenario.tasks?.every((task) => !windowPattern.test(task.referenceQuery))).toBe(true)
    expect(byId.airline.scenario.tasks?.slice(0, 8).every((task) => !windowPattern.test(task.referenceQuery))).toBe(true)
    expect(byId.airline.scenario.tasks?.slice(8).every((task) => windowPattern.test(task.referenceQuery))).toBe(true)
  })

  it('объявляет все суррогатные id как IDENTITY', () => {
    for (const preset of presets) {
      const tables = Object.keys(preset.scenario.data).filter((table) => preset.scenario.data[table][0]?.id !== undefined)
      for (const table of tables) {
        const definition = preset.scenario.schemaSql.match(new RegExp(`CREATE TABLE ${table} \\(([\\s\\S]*?)\\n\\);`))?.[1]
        expect(definition).toContain('id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      }
    }
  })

  it('соблюдает объёмы данных', () => {
    expect(byId.shop.scenario.data.products).toHaveLength(16)
    expect(byId.shop.scenario.data.orders).toHaveLength(16)
    expect(byId.shop.scenario.data.order_items).toHaveLength(32)
    expect(byId.cinema.scenario.data.movies).toHaveLength(13)
    expect(byId.cinema.scenario.data.movie_genres).toHaveLength(24)
    expect(byId.cinema.scenario.data.watch_history).toHaveLength(36)
    expect(byId.airline.scenario.data.airports).toHaveLength(8)
    expect(byId.airline.scenario.data.flights).toHaveLength(15)
    expect(byId.airline.scenario.data.bookings).toHaveLength(14)
    expect(byId.airline.scenario.data.tickets).toHaveLength(29)
    expect(byId.airline.scenario.data.ticket_flights).toHaveLength(49)
    expect(byId.airline.scenario.data.boarding_passes).toHaveLength(35)
  })
})

describe('интернет-магазин', () => {
  const data = byId.shop.scenario.data

  it('содержит учебные краевые случаи каталога и клиентов', () => {
    expect(data.products.filter((product) => product.is_active && Number(product.price) > 3000).length).toBeGreaterThanOrEqual(6)
    expect(data.products.some((product) => !product.is_active && Number(product.price) > 3000)).toBe(true)
    expect(data.customers.filter((customer) => ['Москва', 'Санкт-Петербург'].includes(String(customer.city)) && String(customer.registered_at) >= '2026-01-01' && String(customer.registered_at) <= '2026-06-30').length).toBeGreaterThanOrEqual(3)
    expect(new Set(data.orders.map((order) => order.status))).toEqual(new Set(['new', 'paid', 'delivered', 'cancelled']))
    const pro = data.products.filter((product) => String(product.name).toLowerCase().includes('pro'))
    expect(new Set(pro.filter((product) => Number(product.stock_qty) > 0).map((product) => product.category_id)).size).toBeGreaterThanOrEqual(2)
    expect(pro.some((product) => product.stock_qty === 0)).toBe(true)
    const withoutOrders = data.customers.filter((customer) => !data.orders.some((order) => order.customer_id === customer.id))
    expect(withoutOrders).toHaveLength(2)
    expect(withoutOrders.some((customer) => customer.city === null)).toBe(true)
    expect(data.products.filter((product) => !data.order_items.some((item) => item.product_id === product.id))).toHaveLength(2)
    expect(data.categories.some((category) => !data.products.some((product) => product.category_id === category.id))).toBe(true)
  })

  it('различает текущую и историческую цену и статусы продаж', () => {
    expect(data.order_items.filter((item) => item.unit_price !== data.products.find((product) => product.id === item.product_id)?.price).length).toBeGreaterThanOrEqual(2)
    const deliveredByCustomer = new Map<number, number>()
    const cancelledByCustomer = new Map<number, number>()
    for (const item of data.order_items) {
      const order = data.orders.find((candidate) => candidate.id === item.order_id)!
      const target = order.status === 'delivered' ? deliveredByCustomer : order.status === 'cancelled' ? cancelledByCustomer : null
      target?.set(Number(order.customer_id), (target.get(Number(order.customer_id)) ?? 0) + Number(item.unit_price) * Number(item.quantity))
    }
    expect([...deliveredByCustomer.values()].filter((total) => total > 15000).length).toBeGreaterThanOrEqual(2)
    expect(data.customers.some((customer) => (deliveredByCustomer.get(Number(customer.id)) ?? 0) <= 15000 && (cancelledByCustomer.get(Number(customer.id)) ?? 0) > 15000)).toBe(true)
    const deliveredCategoryIds = new Set(data.order_items.filter((item) => data.orders.find((order) => order.id === item.order_id)?.status === 'delivered').map((item) => data.products.find((product) => product.id === item.product_id)?.category_id))
    expect(data.categories.some((category) => data.products.some((product) => product.category_id === category.id) && !deliveredCategoryIds.has(category.id))).toBe(true)
  })
})

describe('онлайн-кинотеатр', () => {
  const data = byId.cinema.scenario.data

  it('содержит пустые сущности, тарифы и корректные реферальные цепочки', () => {
    expect(data.movies.filter((movie) => Number(movie.release_year) >= 2020 && Number(movie.age_rating) <= 16 && Number(movie.duration_min) > 100).length).toBeGreaterThanOrEqual(4)
    expect(data.movies.some((movie) => Number(movie.release_year) >= 2020 && movie.age_rating === 18 && Number(movie.duration_min) > 100)).toBe(true)
    expect(data.users.filter((user) => user.invited_by === null)).toHaveLength(4)
    expect(data.users.filter((user) => !data.subscriptions.some((subscription) => subscription.user_id === user.id))).toHaveLength(2)
    expect(new Set(data.subscriptions.map((subscription) => subscription.plan))).toEqual(new Set(['basic', 'standard', 'premium']))
    expect(new Set(data.subscriptions.map((subscription) => subscription.status))).toEqual(new Set(['active', 'expired', 'cancelled']))
    for (const user of data.users.filter((candidate) => candidate.invited_by !== null)) {
      const inviter = data.users.find((candidate) => candidate.id === user.invited_by)!
      expect(String(user.registered_at) >= String(inviter.registered_at)).toBe(true)
    }
    expect(data.genres.some((genre) => !data.movie_genres.some((link) => link.genre_id === genre.id))).toBe(true)
    expect(data.movies.filter((movie) => !data.watch_history.some((view) => view.movie_id === movie.id))).toHaveLength(2)
    expect(data.users.filter((user) => !data.watch_history.some((view) => view.user_id === user.id))).toHaveLength(2)
  })

  it('поддерживает месячные агрегаты, границу 80% и ничью рейтингов', () => {
    const months = new Map<string, number>()
    for (const view of data.watch_history) {
      const movie = data.movies.find((candidate) => candidate.id === view.movie_id)!
      expect(Number(view.watched_min)).toBeLessThanOrEqual(Number(movie.duration_min))
      const month = String(view.watched_at).slice(0, 7)
      months.set(month, (months.get(month) ?? 0) + 1)
    }
    expect(months.size).toBeGreaterThanOrEqual(4)
    expect([...months.values()].filter((count) => count >= 4).length).toBeGreaterThanOrEqual(2)
    expect(data.watch_history.some((view) => view.user_rating === null)).toBe(true)
    expect(data.watch_history.some((view) => Number(view.watched_min) === Number(data.movies.find((movie) => movie.id === view.movie_id)?.duration_min) * 0.8)).toBe(true)
    expect(data.watch_history.some((view) => Number(view.watched_min) < Number(data.movies.find((movie) => movie.id === view.movie_id)?.duration_min) * 0.8)).toBe(true)
    expect(data.movies.some((movie) => data.watch_history.filter((view) => view.movie_id === movie.id && view.user_rating !== null).length === 1 && data.watch_history.find((view) => view.movie_id === movie.id && view.user_rating !== null)?.user_rating === 10)).toBe(true)
  })
})

describe('авиаперелёты', () => {
  const data = byId.airline.scenario.data

  it('сохраняет стоимость броней и уникальность посадочных мест', () => {
    expect(data.aircrafts.filter((aircraft) => Number(aircraft.capacity) >= 40 && Number(aircraft.range_km) > 2500).length).toBeGreaterThanOrEqual(3)
    expect(data.airports.some((airport) => !data.flights.some((flight) => flight.departure_airport === airport.code || flight.arrival_airport === airport.code))).toBe(true)
    expect(new Set(data.flights.map((flight) => flight.status))).toEqual(new Set(['scheduled', 'departed', 'arrived', 'cancelled']))
    expect(data.flights.some((flight) => flight.status !== 'cancelled' && !data.ticket_flights.some((segment) => segment.flight_id === flight.id))).toBe(true)
    for (const booking of data.bookings) {
      const ticketIds = data.tickets.filter((ticket) => ticket.booking_id === booking.id).map((ticket) => ticket.id)
      const total = data.ticket_flights.filter((segment) => ticketIds.includes(segment.ticket_id)).reduce((sum, segment) => sum + Number(segment.price), 0)
      expect(Number(booking.total_amount)).toBe(total)
    }
    for (const flight of data.flights) {
      const segmentIds = data.ticket_flights.filter((segment) => segment.flight_id === flight.id).map((segment) => segment.id)
      const passes = data.boarding_passes.filter((pass) => segmentIds.includes(pass.ticket_flight_id))
      expect(new Set(passes.map((pass) => pass.seat_no)).size).toBe(passes.length)
      expect(new Set(passes.map((pass) => pass.boarding_no)).size).toBe(passes.length)
    }
  })

  it('соблюдает хронологию и содержит пересадки и равные задержки', () => {
    for (const flight of data.flights) {
      for (const value of [flight.scheduled_departure, flight.scheduled_arrival, flight.actual_departure, flight.actual_arrival]) {
        if (value !== null) expect(String(value)).toMatch(/:\d{2}:00$/)
      }
      expect(timestamp(flight.scheduled_arrival)).toBeGreaterThan(timestamp(flight.scheduled_departure))
    }
    for (const pass of data.boarding_passes) {
      const segment = data.ticket_flights.find((candidate) => candidate.id === pass.ticket_flight_id)!
      const ticket = data.tickets.find((candidate) => candidate.id === segment.ticket_id)!
      const booking = data.bookings.find((candidate) => candidate.id === ticket.booking_id)!
      const flight = data.flights.find((candidate) => candidate.id === segment.flight_id)!
      expect(timestamp(pass.issued_at)).toBeGreaterThanOrEqual(timestamp(booking.booked_at))
      expect(timestamp(pass.issued_at)).toBeLessThan(timestamp(flight.scheduled_departure))
      expect(timestamp(booking.booked_at)).toBeLessThan(timestamp(flight.scheduled_departure))
    }
    expect(data.tickets.filter((ticket) => data.ticket_flights.filter((segment) => segment.ticket_id === ticket.id).length >= 2).length).toBeGreaterThanOrEqual(2)
    const delays = data.flights.filter((flight) => flight.actual_arrival).map((flight) => timestamp(flight.actual_arrival) - timestamp(flight.scheduled_arrival))
    expect(new Set(delays).size).toBeLessThan(delays.length)
  })
})
