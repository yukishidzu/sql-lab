import { expect, test } from '@playwright/test'

test('NULL вводится словом без дополнительной галочки', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Интернет-магазин.*5 таблиц/s }).click()
  await expect(page.getByRole('button', { name: 'Выполнить', exact: true })).toBeVisible({ timeout: 90000 })
  await page.locator('.react-flow__node').filter({ hasText: 'customers' }).getByText('customers', { exact: true }).click()
  await page.getByRole('button', { name: 'Строка', exact: true }).click()
  await page.getByRole('button', { name: 'Случайные значения' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('input[type=checkbox]')).toHaveCount(0)
  const emailInput = dialog.locator('label').filter({ hasText: /^email/ }).locator('input')
  await expect(emailInput).not.toHaveValue('')
  const email = await emailInput.inputValue()
  await dialog.locator('label').filter({ hasText: /^city/ }).locator('input').fill('NULL')
  await page.getByRole('button', { name: 'Сохранить строку' }).click()
  await page.getByRole('button', { name: email, exact: true }).click()
  await expect(dialog.locator('label').filter({ hasText: /^city/ }).locator('input')).toHaveValue('NULL')
})

test('генератор создаёт валидную строку, а черновик переживает закрытие вкладки', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Авиаперелёты.*7 таблиц/s }).click()
  await expect(page.getByRole('button', { name: 'Выполнить', exact: true })).toBeVisible({ timeout: 90000 })
  await page.locator('.react-flow__node').filter({ hasText: 'bookings' }).getByText('bookings', { exact: true }).click()
  await page.getByRole('button', { name: 'Строка', exact: true }).click()
  await page.getByRole('button', { name: 'Случайные значения' }).click()
  const dialog = page.getByRole('dialog')
  const timestamp = dialog.locator('label').filter({ hasText: /^booked_at/ }).locator('input:not([type=checkbox])')
  await expect(timestamp).toHaveValue(/^2026-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/)
  const reference = dialog.locator('label').filter({ hasText: /^book_ref/ }).locator('input:not([type=checkbox])')
  const generatedReference = await reference.inputValue()
  await page.getByRole('button', { name: 'Сохранить строку' }).click()
  await expect(page.getByRole('button', { name: generatedReference, exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Строка', exact: true }).click()
  await reference.fill('DRAFT-BOOK')
  await expect.poll(() => page.evaluate(() => Object.keys(localStorage).some((key) => key.includes('row-draft') && key.endsWith(':bookings')))).toBe(true)
  const url = page.url()
  await page.close()
  page = await context.newPage()
  await page.goto(url)
  await expect(page.getByRole('button', { name: 'Выполнить', exact: true })).toBeVisible({ timeout: 90000 })
  await page.locator('.react-flow__node').filter({ hasText: 'bookings' }).getByText('bookings', { exact: true }).click()
  await expect(page.getByText('Несохранённый черновик восстановлен')).toBeVisible()
  await expect(page.getByRole('dialog').locator('label').filter({ hasText: /^book_ref/ }).locator('input:not([type=checkbox])')).toHaveValue('DRAFT-BOOK')
})
